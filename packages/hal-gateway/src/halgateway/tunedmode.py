"""The generated llama.cpp mode `tuned`: one preset per role served from GGUF files.

`hal tune --write` calls `render` with the tuned settings and `write` to put `tuned.ini` in the
user's modes directory, beside the bundled modes (which keep working). Decisions:

- Settings come from `halkit.tuning`, so context and offload are never hard-coded here.
- The file goes through the same checks as any mode (`modes.render_mode`): every weight file
  must be pinned in the model manifest, and no forbidden key is written.
- Presets load on demand (`load-on-startup = false`) because the roles are planned one at a
  time, not as a set that fits in memory together.
- `n-gpu-layers = 99` means "all layers" (the value existing bundled modes use). A
  mixture-of-experts role that does not fit keeps every layer on the GPU and the routed experts
  of `n-cpu-moe` layers in RAM (llama-server `--n-cpu-moe`), as the bundled hybrid modes do.
- A write often plans only some roles (`hal tune --role`, `hal models assign`, the screens write
  the changed ones), so `read` gives back the presets already in the file for the caller to keep.
- The `embeddings` key for the embed role and `tensor-split` follow llama-server's argument
  names [unverified against every llama.cpp build: check `hal-gateway render tuned`].
"""

from __future__ import annotations

import configparser
from dataclasses import dataclass
from pathlib import Path

from halkit import files
from halkit.tuning import ALL_LAYERS

MODE_NAME = "tuned"
ALL_LAYERS_VALUE = 99
PARALLEL_SLOTS = 1  # one slot per preset: the context is sized for a single conversation
# llama-server's `--fit` (on by default in b11512) moves unset settings to keep a 1 GiB margin;
# the tuned numbers are already sized, and a setting the user made past the guidance must stay
FIT = "off"


@dataclass(frozen=True)
class Preset:
    """The settings of one role's preset."""

    role: str
    model_path: Path
    context: int
    kv_type: str
    gpu_layers: int  # `halkit.tuning.ALL_LAYERS`, a count, or 0
    tensor_split: tuple[float, ...] = ()
    temperature: float = -1.0  # -1 = leave the model's default
    embedding: bool = False
    mmproj: Path | None = None
    cpu_moe: int = 0  # layers whose routed experts stay in RAM
    draft_path: Path | None = None  # draft model for speculative decoding
    spec_type: str = ""  # llama-server `--spec-type`: draft-mtp, draft-dflash, ...
    draft_max: int = 0  # tokens drafted per step


def preset_name(role: str) -> str:
    """The preset (and so the upstream model) name of `role`."""
    return f"{MODE_NAME}-{role}"


def _section(p: Preset) -> list[str]:
    layers = ALL_LAYERS_VALUE if p.gpu_layers == ALL_LAYERS else p.gpu_layers
    lines = [
        f"[{preset_name(p.role)}]",
        f"model = {p.model_path}",
        f"ctx-size = {p.context}",
        f"n-gpu-layers = {layers}",
        f"cache-type-k = {p.kv_type}",
        f"cache-type-v = {p.kv_type}",
    ]
    if p.cpu_moe:
        lines.append(f"n-cpu-moe = {p.cpu_moe}")
    if p.draft_path:
        lines += [
            f"model-draft = {p.draft_path}",
            f"spec-type = {p.spec_type}",
            f"spec-draft-n-max = {p.draft_max}",
            f"n-gpu-layers-draft = {ALL_LAYERS_VALUE}",  # the draft always fits beside the model (tuning)
            f"cache-type-k-draft = {p.kv_type}",
            f"cache-type-v-draft = {p.kv_type}",
        ]
    if p.tensor_split:
        lines.append("tensor-split = " + ",".join(f"{share:g}" for share in p.tensor_split))
    if p.temperature >= 0:
        lines.append(f"temp = {p.temperature:g}")
    if p.embedding:
        lines.append("embeddings = true")
    if p.mmproj:
        lines.append(f"mmproj = {p.mmproj}")
    return lines


def render(presets: list[Preset]) -> str:
    """The text of `tuned.ini`; raises `ValueError` when `presets` is empty."""
    if not presets:
        raise ValueError("no GGUF role to put in the tuned mode")
    main = next((p for p in presets if p.role == "chat"), presets[0])
    lines = [
        "; Mode tuned: generated by `hal tune --write` from this machine's hardware. Do not edit;",
        "; run `hal tune` again to change it.",
        "version = 1",
        "",
        "[hal]",
        "description = generated by hal tune for this machine",
        f"main = {preset_name(main.role)}",
        "",
        "[*]",
        "jinja = true",
        "flash-attn = on",
        f"fit = {FIT}",
        f"parallel = {PARALLEL_SLOTS}",
        "load-on-startup = false",
        "",
    ]
    for preset in presets:
        lines += [*_section(preset), ""]
    return "\n".join(lines)


def read(path: Path) -> list[Preset]:
    """The presets of a `tuned.ini` that `render` wrote; empty when the file does not exist.

    Raises `ValueError` when the file is not one `render` could have written.
    """
    if not Path(path).exists():
        return []
    parser = configparser.ConfigParser(interpolation=None, default_section="*")
    try:
        # `version = 1` comes before the first section, which configparser refuses on its own
        parser.read_string("[__top__]\n" + Path(path).read_text(encoding="utf-8"), source=str(path))
    except configparser.Error as exc:
        raise ValueError(f"{path}: {exc}") from exc
    prefix, out = preset_name(""), []
    for section in parser.sections():
        if not section.startswith(prefix):
            continue
        sec = parser[section]
        try:
            layers = int(sec["n-gpu-layers"])
            split = tuple(float(v) for v in sec["tensor-split"].split(",")) if "tensor-split" in sec else ()
            out.append(
                Preset(
                    role=section.removeprefix(prefix),
                    model_path=Path(sec["model"]),
                    context=int(sec["ctx-size"]),
                    kv_type=sec["cache-type-k"],
                    gpu_layers=ALL_LAYERS if layers == ALL_LAYERS_VALUE else layers,
                    tensor_split=split,
                    temperature=float(sec.get("temp", "-1")),
                    embedding=sec.get("embeddings") == "true",
                    mmproj=Path(sec["mmproj"]) if "mmproj" in sec else None,
                    cpu_moe=int(sec.get("n-cpu-moe", "0")),
                    draft_path=Path(sec["model-draft"]) if "model-draft" in sec else None,
                    spec_type=sec.get("spec-type", ""),
                    draft_max=int(sec.get("spec-draft-n-max", "0")),
                )
            )
        except (KeyError, ValueError) as exc:
            raise ValueError(f"{path}: preset [{section}] is not one hal tune writes ({exc})") from exc
    return out


def write(presets: list[Preset], modes_dir: Path) -> Path:
    """Writes `tuned.ini` into `modes_dir` (mode 0600) and returns its path."""
    target = Path(modes_dir) / f"{MODE_NAME}.ini"
    files.write_atomic(target, render(presets))
    return target
