"""Client `ssh_config` rendering, `ssh` discovery and the argv builders (design 07, Client ssh_config).

The generated file is used only with `ssh -F`, so the user's own `~/.ssh/config` never changes
a connection. Paths are written with forward slashes in double quotes on every OS. Only the
`ssh` binary is ever named in an argv built here (REQ-RMT-28), and every option is explicit
so a harness or a CI runner never gets a prompt.
"""

from __future__ import annotations

import os
import shutil
from pathlib import Path

from .model import Profile, ProfilePaths

WINDOWS_SSH = Path("System32") / "OpenSSH" / "ssh.exe"


class SshNotFound(FileNotFoundError):
    """No usable OpenSSH client was found."""


def alias(profile: Profile, role: str) -> str:
    """The ssh host alias for a role: `hal-<profile>-tunnel` or `hal-<profile>-mcp`."""
    return f"hal-{profile.name}-{role}"


def find_ssh(override: str = "") -> Path:
    """Finds `ssh`: the `[remote].ssh` override, else the Windows OpenSSH, else `PATH`."""
    if override:
        path = Path(override).expanduser()
        if not path.is_file():
            raise SshNotFound(f"[remote].ssh is {override!r}, which is not a file")
        return path
    if os.name == "nt":
        windows = Path(os.environ.get("SystemRoot", r"C:\Windows")) / WINDOWS_SSH
        if windows.is_file():
            return windows
    found = shutil.which("ssh")
    if found is None:
        raise SshNotFound("no OpenSSH client found: install OpenSSH or set [remote].ssh")
    return Path(found)


def find_ssh_keygen(ssh: Path) -> Path:
    """Finds `ssh-keygen` beside `ssh`, else on `PATH`."""
    for name in ("ssh-keygen", "ssh-keygen.exe"):
        beside = ssh.with_name(name)
        if beside.is_file():
            return beside
    found = shutil.which("ssh-keygen")
    if found is None:
        raise SshNotFound("no ssh-keygen found beside ssh or on PATH")
    return Path(found)


def find_ssh_keyscan(ssh: Path) -> Path:
    """Finds `ssh-keyscan` beside `ssh`, else on `PATH`."""
    for name in ("ssh-keyscan", "ssh-keyscan.exe"):
        beside = ssh.with_name(name)
        if beside.is_file():
            return beside
    found = shutil.which("ssh-keyscan")
    if found is None:
        raise SshNotFound("no ssh-keyscan found beside ssh or on PATH")
    return Path(found)


def _q(path: Path) -> str:
    """Double-quotes a path with forward slashes; ssh_config unquotes it."""
    text = path.as_posix()
    if '"' in text or "\n" in text:
        raise ValueError(f"path {text!r} cannot be written into ssh_config")
    return f'"{text}"'


def render(profile: Profile, paths: ProfilePaths) -> str:
    """Renders the `ssh_config` for `profile`."""
    t, m = alias(profile, "tunnel"), alias(profile, "mcp")
    stamp = f" on {profile.created}" if profile.created else ""
    s = profile.tunnel
    lines = [
        f"# Generated by hal-remote setup{stamp}. Rerun setup instead of editing.",
        f"Host {t} {m}",
        f"  HostName {profile.host}",
        f"  User {profile.user}",
        f"  Port {profile.port}",
        f"  HostKeyAlias hal-{profile.name}",
        f"  UserKnownHostsFile {_q(paths.known_hosts)}",
        "  GlobalKnownHostsFile none",
        "  StrictHostKeyChecking yes",
        "  UpdateHostKeys no",
        "  CheckHostIP no",
        "  IdentitiesOnly yes",
        "  IdentityAgent none",
        "  BatchMode yes",
        f"  ConnectTimeout {s.connect_timeout_s}",
        f"  ServerAliveInterval {s.server_alive_interval_s}",
        f"  ServerAliveCountMax {s.server_alive_count_max}",
        "  ForwardAgent no",
        "  ForwardX11 no",
        "  ControlMaster no",
        "  ControlPath none",
        "  PermitLocalCommand no",
        "  LogLevel ERROR",
        f"Host {t}",
        f"  IdentityFile {_q(paths.tunnel_key)}",
        "  SessionType none",
        "  ExitOnForwardFailure yes",
    ]
    lines += [f"  LocalForward 127.0.0.1:{f.local_port} 127.0.0.1:{f.remote_port}" for f in profile.forwards]
    lines += [
        f"Host {m}",
        f"  IdentityFile {_q(paths.mcp_key)}",
        "  RequestTTY no",
        "  ClearAllForwardings yes",
    ]
    return "\n".join(lines) + "\n"


def tunnel_argv(profile: Profile, paths: ProfilePaths, ssh: Path) -> list[str]:
    """The argv of the long-running tunnel: `ssh -F <config> -N <alias>`."""
    return [str(ssh), "-F", paths.ssh_config.as_posix(), "-N", alias(profile, "tunnel")]


def mcp_argv(profile: Profile, paths: ProfilePaths, ssh: Path) -> list[str]:
    """The argv of an MCP stdio session: `ssh -F <config> -T <alias>`; the forced command runs."""
    return [str(ssh), "-F", paths.ssh_config.as_posix(), "-T", alias(profile, "mcp")]
