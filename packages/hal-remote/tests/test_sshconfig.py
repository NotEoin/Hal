"""Tests for `halremote.sshconf`: the rendered file, discovery, argv builders and `ssh -G`."""

import shutil
import subprocess
from pathlib import Path, PurePosixPath, PureWindowsPath

import pytest

from halremote import sshconf
from halremote.model import Forward, Profile, ProfilePaths

SSH = shutil.which("ssh")


def _paths(root) -> ProfilePaths:
    return ProfilePaths(
        root=root, ssh_config=root / "ssh_config", known_hosts=root / "known_hosts",
        tunnel_key=root / "tunnel_ed25519", mcp_key=root / "mcp_ed25519",
        token=root / "gateway-token", state=root / "state",
    )  # fmt: skip


def _profile(created="2026-10-23T18:00:00Z") -> Profile:
    return Profile(
        "desktop", "laptop", "desk.lan", "user", 22, (Forward("gateway", 8741, 8741),), created=created
    )


GOLDEN_POSIX = """\
# Generated by hal-remote setup on 2026-10-23T18:00:00Z. Rerun setup instead of editing.
Host hal-desktop-tunnel hal-desktop-mcp
  HostName desk.lan
  User user
  Port 22
  HostKeyAlias hal-desktop
  UserKnownHostsFile "/home/me/.config/hal/remote/desktop/known_hosts"
  GlobalKnownHostsFile none
  StrictHostKeyChecking yes
  UpdateHostKeys no
  CheckHostIP no
  IdentitiesOnly yes
  IdentityAgent none
  BatchMode yes
  ConnectTimeout 10
  ServerAliveInterval 15
  ServerAliveCountMax 3
  ForwardAgent no
  ForwardX11 no
  ControlMaster no
  ControlPath none
  PermitLocalCommand no
  LogLevel ERROR
Host hal-desktop-tunnel
  IdentityFile "/home/me/.config/hal/remote/desktop/tunnel_ed25519"
  SessionType none
  ExitOnForwardFailure yes
  LocalForward 127.0.0.1:8741 127.0.0.1:8741
Host hal-desktop-mcp
  IdentityFile "/home/me/.config/hal/remote/desktop/mcp_ed25519"
  RequestTTY no
  ClearAllForwardings yes
"""


def test_posix_render_matches_the_golden():
    root = PurePosixPath("/home/me/.config/hal/remote/desktop")
    assert sshconf.render(_profile(), _paths(root)) == GOLDEN_POSIX  # type: ignore[arg-type]  # pure paths


def test_windows_paths_are_written_with_forward_slashes():
    root = PureWindowsPath("C:/Users/me/.config/hal/remote/desktop")
    text = sshconf.render(_profile(), _paths(root))  # type: ignore[arg-type]  # pure paths
    assert 'IdentityFile "C:/Users/me/.config/hal/remote/desktop/mcp_ed25519"' in text
    assert "\\" not in text


def test_render_without_a_created_stamp_has_a_plain_header():
    assert sshconf.render(_profile(created=""), _paths(PurePosixPath("/x"))).startswith(  # type: ignore[arg-type]
        "# Generated by hal-remote setup. Rerun"
    )


def test_path_with_a_quote_is_refused():
    with pytest.raises(ValueError):
        sshconf.render(_profile(), _paths(PurePosixPath('/x"y')))  # type: ignore[arg-type]


def test_argv_builders_name_only_ssh_and_the_generated_config(tmp_path):
    paths, ssh = _paths(tmp_path), Path("/usr/bin/ssh")
    assert sshconf.tunnel_argv(_profile(), paths, ssh) == [
        "/usr/bin/ssh", "-F", str(tmp_path / "ssh_config"), "-N", "hal-desktop-tunnel",
    ]  # fmt: skip
    assert sshconf.mcp_argv(_profile(), paths, ssh)[-2:] == ["-T", "hal-desktop-mcp"]


def test_override_is_used_and_must_exist(tmp_path):
    fake = tmp_path / "ssh"
    fake.write_text("")
    assert sshconf.find_ssh(str(fake)) == fake
    with pytest.raises(sshconf.SshNotFound):
        sshconf.find_ssh(str(tmp_path / "missing"))


def test_discovery_without_ssh_on_path_fails_loudly(monkeypatch):
    monkeypatch.setattr(sshconf.shutil, "which", lambda _name: None)
    monkeypatch.setattr(sshconf.os, "name", "posix")
    with pytest.raises(sshconf.SshNotFound, match="set \\[remote\\].ssh"):
        sshconf.find_ssh()


def test_ssh_keygen_is_found_beside_ssh(tmp_path):
    (tmp_path / "ssh").write_text("")
    (tmp_path / "ssh-keygen").write_text("")
    assert sshconf.find_ssh_keygen(tmp_path / "ssh") == tmp_path / "ssh-keygen"


@pytest.mark.skipif(SSH is None, reason="ssh is not installed")
def test_ssh_g_resolves_the_rendered_file_as_designed(tmp_path):
    root = tmp_path / "with space"
    root.mkdir()
    paths = _paths(root)
    paths.ssh_config.write_text(sshconf.render(_profile(), paths))

    def resolve(host):
        out = subprocess.run(
            [SSH, "-G", "-F", str(paths.ssh_config), host],
            capture_output=True,
            text=True,
            timeout=30,
            check=True,
        ).stdout
        return {line.split(" ", 1)[0]: line.split(" ", 1)[1] for line in out.splitlines() if " " in line}

    tunnel, mcp = resolve("hal-desktop-tunnel"), resolve("hal-desktop-mcp")
    assert tunnel["identityfile"] == str(paths.tunnel_key)
    assert tunnel["localforward"] == "[127.0.0.1]:8741 [127.0.0.1]:8741"
    assert tunnel["sessiontype"] == "none"
    assert tunnel["identityagent"] == "none"
    assert tunnel["globalknownhostsfile"] == "none"
    assert tunnel["userknownhostsfile"] == str(paths.known_hosts)
    assert tunnel["hostkeyalias"] == "hal-desktop"
    assert mcp["clearallforwardings"] == "yes"
    assert mcp["requesttty"] == "false"
